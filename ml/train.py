"""Train and evaluate the CortexAI Open model on the simulated cohort.

Unit of prediction: one clinic visit (months 1-24). Label: biopsy-proven TCMR or ABMR within the
next 12 months (borderline excluded). Patient-level split: nobody appears in train and test.
Usage: python ml/train.py [n_patients]
"""
import json
import sys
from pathlib import Path

import joblib
import numpy as np
from sklearn.calibration import CalibratedClassifierCV
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, brier_score_loss, roc_auc_score
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from cortex_ml.sim import FEATURES, training_table  # noqa: E402

N = int(sys.argv[1]) if len(sys.argv) > 1 else 6000
df = training_table(N)
X, y, g = df[FEATURES], df["label"], df["patient"]
tr, te = next(GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=0).split(X, y, g))
Xtr, Xte, ytr, yte = X.iloc[tr], X.iloc[te], y.iloc[tr], y.iloc[te]

gbm = CalibratedClassifierCV(
    HistGradientBoostingClassifier(max_iter=400, learning_rate=0.04, max_leaf_nodes=24, l2_regularization=1.0,
                                   random_state=0), method="isotonic", cv=3).fit(Xtr, ytr)
baseline = make_pipeline(SimpleImputer(strategy="median"), StandardScaler(), LogisticRegression(max_iter=2000)).fit(Xtr, ytr)


def scores(p):
    bins = np.quantile(p, np.linspace(0, 1, 11))
    idx = np.clip(np.digitize(p, bins[1:-1]), 0, 9)
    cal = [{"predicted": round(float(p[idx == k].mean()), 3), "observed": round(float(yte.values[idx == k].mean()), 3)}
           for k in range(10) if (idx == k).any()]
    return {"roc_auc": round(roc_auc_score(yte, p), 3), "pr_auc": round(average_precision_score(yte, p), 3),
            "brier": round(brier_score_loss(yte, p), 4), "calibration_deciles": cal}


# Reference "typical stable recipient" used for explanations
reference = {f: float(np.nanmedian(Xtr[f])) for f in FEATURES}
reference.update({"dsa_mfi_max": 0.0, "dsa_class2": 0.0, "bk_viremia": 0.0, "prior_rejection": 0.0, "dgf": 0.0,
                  "retransplant": 0.0, "egfr_change_3m": 0.0, "ddcfdna": 0.3})

metrics = {
    "model": "Calibrated gradient boosting (scikit-learn HistGradientBoosting + isotonic calibration)",
    "explainer": "Counterfactual reset per factor on the production model (percentage points of risk)",
    "target": "Biopsy-proven TCMR or ABMR within 12 months of the visit",
    "unit": "Clinic visit, months 1-24 post-transplant",
    "inputs": "Recipient/donor baseline, HLA (A/B/DR mismatch, class II eplets, PIRCHE-II), cPRA, eGFR (CKD-EPI 2021) and its 3-month change, UPCR, tacrolimus trough/CV/TTR, dd-cfDNA, DSA (MFI, class), BK, prior rejection",
    "n_patients": int(df.patient.nunique()), "n_visits_train": int(len(tr)), "n_visits_test": int(len(te)),
    "event_rate": round(float(y.mean()), 3),
    "gbm": scores(gbm.predict_proba(Xte)[:, 1]), "logistic": scores(baseline.predict_proba(Xte)[:, 1]),
    "data": "Fully synthetic cohort generated by ml/cortex_ml/sim.py. No real patient data.",
    "limitations": [
        "Performance on synthetic data does not predict performance on real patients: the model has learned the simulator.",
        "Requires retrospective validation on local cohorts and prospective silent-mode evaluation before any clinical use.",
        "Eplet and PIRCHE-II values are simulated; production use requires HLAMatchmaker / PIRCHE-II from high-resolution typing.",
        "Not modelled yet: CMV, primary kidney disease and recurrence risk, MMF/steroid exposure, blood pressure, PTDM.",
        "Not a medical device. Decision support only; the treating clinician decides.",
    ],
}
(HERE / "model").mkdir(exist_ok=True)
joblib.dump({"gbm": gbm, "features": FEATURES, "reference": reference}, HERE / "model" / "cortex_open.joblib")
(HERE / "model" / "metrics.json").write_text(json.dumps(metrics, indent=2))
print({"patients": metrics["n_patients"], "event_rate": metrics["event_rate"], "gbm_auc": metrics["gbm"]["roc_auc"],
       "baseline_auc": metrics["logistic"]["roc_auc"], "pr_auc": metrics["gbm"]["pr_auc"], "brier": metrics["gbm"]["brier"]})
