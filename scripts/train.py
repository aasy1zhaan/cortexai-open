"""Train the CortexAI Open demo model on the simulated cohort.

Unit of prediction: one clinic visit. Label: biopsy-proven TCMR or ABMR within the next
12 months (borderline excluded). Split is by patient so no patient appears in both sets.
"""
import json
import sys
from pathlib import Path

import joblib
import numpy as np
from sklearn.calibration import CalibratedClassifierCV
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, brier_score_loss, roc_auc_score
from sklearn.model_selection import GroupShuffleSplit
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from cortex.sim import FEATURES, training_table  # noqa: E402

N = int(sys.argv[1]) if len(sys.argv) > 1 else 6000
df = training_table(N)
X, y, g = df[FEATURES], df["label"], df["patient"]
tr, te = next(GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=0).split(X, y, g))
Xtr, Xte, ytr, yte = X.iloc[tr], X.iloc[te], y.iloc[tr], y.iloc[te]

gbm = CalibratedClassifierCV(
    HistGradientBoostingClassifier(max_iter=400, learning_rate=0.04, max_leaf_nodes=24,
                                   l2_regularization=1.0, random_state=0),
    method="isotonic", cv=3).fit(Xtr, ytr)
lr = make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000, C=0.5)).fit(Xtr, ytr)

def scores(p):
    # calibration in deciles
    bins = np.quantile(p, np.linspace(0, 1, 11))
    idx = np.clip(np.digitize(p, bins[1:-1]), 0, 9)
    cal = [{"predicted": round(float(p[idx == k].mean()), 3), "observed": round(float(yte.values[idx == k].mean()), 3)}
           for k in range(10) if (idx == k).any()]
    return {"roc_auc": round(roc_auc_score(yte, p), 3), "pr_auc": round(average_precision_score(yte, p), 3),
            "brier": round(brier_score_loss(yte, p), 4), "calibration_deciles": cal}

metrics = {
    "model": "Calibrated gradient boosting (scikit-learn HistGradientBoosting + isotonic)",
    "explainer": "Standardised logistic regression contributions (log-odds)",
    "target": "Biopsy-proven TCMR or ABMR within 12 months of the visit",
    "unit": "clinic visit, months 1-24 post-transplant",
    "n_patients": int(df.patient.nunique()), "n_visits_train": int(len(tr)), "n_visits_test": int(len(te)),
    "event_rate": round(float(y.mean()), 3),
    "gbm": scores(gbm.predict_proba(Xte)[:, 1]), "logistic": scores(lr.predict_proba(Xte)[:, 1]),
    "data": "Fully synthetic cohort generated by cortex/sim.py. No real patient data.",
    "limitations": [
        "Performance on synthetic data does not predict performance on real patients.",
        "Requires prospective validation on local, real-world cohorts before any clinical use.",
        "Eplet and PIRCHE-II values are simulated; production use requires HLAMatchmaker / PIRCHE integration.",
        "Not a medical device. Decision support only; the treating clinician decides.",
    ],
}
(ROOT / "model").mkdir(exist_ok=True)
joblib.dump({"gbm": gbm, "lr": lr, "features": FEATURES}, ROOT / "model" / "cortex_open.joblib")
(ROOT / "model" / "metrics.json").write_text(json.dumps(metrics, indent=2))
print(json.dumps({k: v for k, v in metrics.items() if k in ("n_patients", "event_rate")}, indent=1),
      {k: metrics[k]["roc_auc"] for k in ("gbm", "logistic")}, metrics["gbm"]["pr_auc"], metrics["gbm"]["brier"])
